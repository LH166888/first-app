// 按食材名返回匹配的 emoji，未命中返回空串
export function emojiForIngredient(name = '') {
  const n = String(name).trim()
  if (!n) return ''
  for (const [key, emoji] of EMOJI_MAP) {
    if (n.includes(key)) return emoji
  }
  return ''
}
